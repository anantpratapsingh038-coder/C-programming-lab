// swap the values of 2 variables with the help of only 2 variables
#include <stdio.h>
int main(){
    int a,b;
    printf("Enter 1st number:\n");
    scanf("%d",&a);
    printf("Enter 2nd number:\n");
    scanf("%d",&b);
    printf("Current values of a = %d and b = %d\n",a,b);
    printf("The swapped values of a = %d and b = %d\n",b,a);
    return 0;
}